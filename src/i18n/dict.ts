export function t(lang: Language, key: string, vars: Record<string, any> = {}): string {
  let str = dict[lang] ? (dict[lang] as any)[key] : (dict['pt'] as any)[key];
  if (!str) return key;
  for (const k in vars) {
    str = str.replace(`{${k}}`, String(vars[k]));
  }
  return str;
}
